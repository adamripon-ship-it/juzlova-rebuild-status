#!/usr/bin/env python3
"""Export the built site as readable Markdown under docs/website/generated/.

Writes a site map (every page in every language, plus redirects), the full
visible copy of every page, and a gallery of every image in img/. Reads only
the generated HTML, sitemaps and redirects.conf, so run it after
build_site.py. CI runs both and fails if the committed export is stale.

    python3 scripts/build_site.py && python3 scripts/export_docs.py
"""
from __future__ import annotations

import html
import os
import re
import shutil
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "website" / "generated"
LANGS = [("cs", "Čeština"), ("en", "English"), ("de", "Deutsch"), ("sk", "Slovenčina")]
SKIP_TAGS = {"script", "style", "svg", "noscript", "template", "iframe"}
SPACED = {"span", "a", "small", "strong", "b", "em", "i", "sup", "sub", "time", "data"}
VOID = {"img", "br", "hr", "input", "meta", "link", "source", "wbr", "col", "area", "embed", "track"}
BLOCK = {"div", "section", "article", "aside", "header", "footer", "ul", "ol", "tr",
         "p", "li", "h1", "h2", "h3", "h4", "h5", "h6", "dt", "dd", "blockquote",
         "figcaption", "td", "th", "summary", "button", "label", "legend", "caption"}
IMG_REF = re.compile(r"(img/[A-Za-z0-9._/-]+\.(?:webp|png|jpe?g|gif|svg|ico))")
GEN_NOTE = ("<!-- Generated by scripts/export_docs.py from the built site. "
            "Do not edit; change the sources and rebuild. -->\n\n")


class PageText(HTMLParser):
    """Collect title, description, alternates and the text inside <main>."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.description = ""
        self.alternates: dict[str, str] = {}
        self.blocks: list[tuple[str, str]] = []
        self._in_title = False
        self._main = 0
        self._skip = 0
        self._stack: list[str] = []
        self._buf: list[str] = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag == "meta" and a.get("name") == "description":
            self.description = a.get("content", "")
        elif tag == "link" and a.get("rel") == "alternate" and a.get("hreflang"):
            self.alternates.setdefault(a["hreflang"], a.get("href", ""))
        if tag == "main":
            self._main += 1
        if not self._main:
            return
        if self._skip:
            if tag not in VOID:
                self._skip += 1
            return
        if tag in SKIP_TAGS or (a.get("aria-hidden") == "true" and tag not in VOID):
            self._skip += 1
            return
        if tag in SPACED:
            self._buf.append(" ")
        elif tag in BLOCK:
            self._flush()
            self._stack.append(tag)
        elif tag == "br":
            self._buf.append(" ")

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        if not self._main:
            return
        if self._skip:
            if tag not in VOID:
                self._skip -= 1
            return
        if tag in SPACED:
            self._buf.append(" ")
        elif tag in BLOCK:
            self._flush()
            if self._stack and self._stack[-1] == tag:
                self._stack.pop()
        if tag == "main":
            self._flush()
            self._main -= 1

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        elif self._main and not self._skip:
            self._buf.append(data)

    def _flush(self):
        text = re.sub(r"\s+", " ", "".join(self._buf)).strip()
        self._buf = []
        if text:
            kind = self._stack[-1] if self._stack else "p"
            if not self.blocks or self.blocks[-1] != (kind, text):
                self.blocks.append((kind, text))


def page_file(url_path: str) -> Path:
    return ROOT / url_path.strip("/") / "index.html" if url_path.strip("/") else ROOT / "index.html"


def read_sitemap(lang: str, base: str) -> list[str]:
    xml = (ROOT / f"sitemap-{lang}.xml").read_text(encoding="utf-8")
    paths = []
    for loc in re.findall(r"<loc>([^<]+)</loc>", xml):
        path = loc.replace(base, "", 1) or "/"
        if path.endswith("/") and page_file(path).exists():
            paths.append(path)
    return paths


def site_base() -> str:
    xml = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
    m = re.search(r"<loc>(https?://[^/<]+)", xml)
    return m.group(1) if m else ""


def parse(path: str) -> PageText:
    p = PageText()
    p.feed(page_file(path).read_text(encoding="utf-8"))
    p.title = re.sub(r"\s+", " ", html.unescape(p.title)).strip()
    return p


def slug_name(path: str) -> str:
    s = path.strip("/")
    for code, _ in LANGS[1:]:
        if s == code or s.startswith(code + "/"):
            s = s[len(code):].strip("/")
    return s or "home"


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def render_copy(lang: str, path: str, page: PageText) -> str:
    out = [GEN_NOTE, f"# {page.title}\n\n",
           f"- **URL:** `{path}`\n",
           f"- **Meta description:** {page.description}\n\n---\n\n"]
    listy = ("li", "dd", "td", "th")
    prev = ""
    for kind, text in page.blocks:
        if prev in listy and kind not in listy:
            out.append("\n")
        prev = kind
        if kind == "h1":
            out.append(f"## {text}\n\n")
        elif kind in ("h2", "h3", "h4", "h5", "h6"):
            level = min(6, int(kind[1]) + 1)
            out.append(f"{'#' * level} {text}\n\n")
        elif kind in listy:
            out.append(f"- {text}\n")
        elif kind in ("button", "label", "legend", "summary"):
            out.append(f"*{kind}:* {text}\n\n")
        elif kind == "blockquote":
            out.append(f"> {text}\n\n")
        else:
            out.append(f"{text}\n\n")
    return "".join(out).rstrip() + "\n"


def human_size(n: int) -> str:
    return f"{n / 1024:.0f} kB" if n < 1024 * 1024 else f"{n / 1024 / 1024:.1f} MB"


def main() -> None:
    base = site_base()
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "copy").mkdir(parents=True)

    pages: dict[str, dict[str, tuple[str, PageText]]] = {}
    image_use: dict[str, set[str]] = {}
    group_of: dict[str, str] = {}

    for lang, _ in LANGS:
        for path in read_sitemap(lang, base):
            page = parse(path)
            # Group translations by the Czech URL in hreflang, else by own path.
            cs = page.alternates.get("cs-CZ", "").replace(base, "", 1)
            key = group_of.get(path) or (cs if cs else path)
            for href in page.alternates.values():
                group_of.setdefault(href.replace(base, "", 1), key)
            pages.setdefault(key, {})[lang] = (path, page)
            for name in set(IMG_REF.findall(page_file(path).read_text(encoding="utf-8"))):
                image_use.setdefault(name, set()).add(path)

    # Copy, one file per page, one index per language.
    for lang, label in LANGS:
        d = OUT / "copy" / lang
        d.mkdir()
        rows = []
        for key in sorted(pages, key=lambda k: (k != "/", k)):
            if lang not in pages[key]:
                continue
            path, page = pages[key][lang]
            fname = slug_name(path) + ".md"
            (d / fname).write_text(render_copy(lang, path, page), encoding="utf-8")
            rows.append(f"| [{md_escape(page.title)}]({fname}) | `{path}` |\n")
        (d / "README.md").write_text(
            GEN_NOTE + f"# All page copy — {label} (`{lang}`)\n\n"
            f"{len(rows)} pages. Each file holds the page title, meta description "
            "and every piece of visible text inside the page body, in reading order.\n\n"
            "| Page | URL |\n|---|---|\n" + "".join(rows), encoding="utf-8")

    # Site map.
    sm = [GEN_NOTE, "# Site map\n\n",
          f"Every page the site publishes, from the four sitemaps. Base URL: `{base}`.\n",
          "A dash means the page exists in Czech only (local landing pages).\n\n",
          "| Page (Czech title) | 🇨🇿 cs | 🇬🇧 en | 🇩🇪 de | 🇸🇰 sk |\n|---|---|---|---|---|\n"]
    for key in sorted(pages, key=lambda k: (k != "/", k)):
        langs = pages[key]
        title = (langs.get("cs") or next(iter(langs.values())))[1].title.split(" — ")[0]
        cells = []
        for lang, _ in LANGS:
            if lang in langs:
                path = langs[lang][0]
                cells.append(f"[`{path}`](copy/{lang}/{slug_name(path)}.md)")
            else:
                cells.append("—")
        sm.append(f"| {md_escape(title)} | " + " | ".join(cells) + " |\n")
    counts = {lang: sum(1 for v in pages.values() if lang in v) for lang, _ in LANGS}
    sm.append("\n**Pages per language:** " + ", ".join(f"{k} {v}" for k, v in counts.items()) + "\n")

    conf = (ROOT / "redirects.conf").read_text(encoding="utf-8")
    redirects = re.findall(r"rewrite \^(\S+?)\(\?:/feed\)\?/\?\$ (\S+) permanent", conf)
    sm.append(f"\n## Redirects (301)\n\n{len(redirects)} old addresses — mostly from the "
              "WordPress site — forward permanently to their current page. Generated from "
              "`LEGACY_REDIRECTS` and `WP_REDIRECTS` in `scripts/build_site.py`.\n\n"
              "| Old address | Goes to |\n|---|---|\n")
    for old, new in redirects:
        old = "/" + old.lstrip("/").replace("\\", "")
        sm.append(f"| `{old}` | `{new.replace(base, '', 1)}` |\n")
    gone = re.search(r'\$uri ~ "(.+?)"\) \{ return 410', conf)
    if gone:
        sm.append("\n## Gone for good (410)\n\nThese answer *410 Gone* so search engines "
                  "drop them: dead WordPress machinery, theme demo posts, feeds, `/archive/` "
                  "and the old status board.\n\n```\n"
                  + gone.group(1).replace("\\", "") + "\n```\n")
    (OUT / "site-map.md").write_text("".join(sm), encoding="utf-8")

    for extra in ["assets/site.css", "assets/site.js", "site.webmanifest"]:
        f = ROOT / extra
        if f.exists():
            for name in set(IMG_REF.findall(f.read_text(encoding="utf-8"))):
                image_use.setdefault(name, set()).add(extra)

    # Image gallery.
    gal = [GEN_NOTE, "# Image gallery\n\n",
           "Every file in `img/`, with its size and the pages that show it. "
           "Where each image came from is in [../05-images.md](../05-images.md).\n\n",
           "| Preview | File | Size | Used on |\n|---|---|---|---|\n"]
    total = 0
    for f in sorted(p for p in (ROOT / "img").rglob("*") if p.is_file()):
        size = f.stat().st_size
        total += size
        rel = f.relative_to(ROOT).as_posix()
        used = sorted(image_use.get(rel, set()))
        use = ", ".join(f"`{u}`" for u in used[:4]) + (f" +{len(used) - 4} more" if len(used) > 4 else "")
        preview = (f'<img src="../../../{rel}" width="120">'
                   if f.suffix.lower() in (".webp", ".png", ".jpg", ".jpeg", ".gif", ".svg") else "")
        gal.append(f"| {preview} | `{rel[4:]}` | {human_size(size)} | {use or 'not referenced by the current site (source, original or spare size)'} |\n")
    gal.append(f"\n**Total:** {human_size(total)} in `img/`.\n")
    (OUT / "images.md").write_text("".join(gal), encoding="utf-8")

    n = sum(len(v) for v in pages.values())
    print(f"export_docs: {n} pages, {len(redirects)} redirects -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    os.chdir(ROOT)
    main()
